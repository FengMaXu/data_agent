interface LanguageContextProps {
    language: Language;
    toggleLanguage: () => void;
    setLanguage: (language: Language) => void;
    t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextProps | undefined>(undefined);

const getInitialLanguage = (): Language => {
    if (typeof window === 'undefined') return 'zh';
    const savedLang = localStorage.getItem('app_language') as Language;
    return savedLang === 'en' || savedLang === 'zh' ? savedLang : 'zh';
};

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
    const [language, setLanguage] = useState<Language>(getInitialLanguage);

    useEffect(() => {
        document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
        document.documentElement.dir = 'ltr';
    }, [language]);

    const toggleLanguage = useCallback(() => {
        const nextLang = language === 'zh' ? 'en' : 'zh';
        setLanguage(nextLang);
        localStorage.setItem('app_language', nextLang);
    }, [language]);

    const updateLanguage = useCallback((nextLanguage: Language) => {
        setLanguage(nextLanguage);
        localStorage.setItem('app_language', nextLanguage);
    }, []);

    const t = useCallback((key: string): string => {
        return translations[language][key] || key;
    }, [language]);

    return (
        <LanguageContext.Provider value={{ language, toggleLanguage, setLanguage: updateLanguage, t }}>
            {children}
        </LanguageContext.Provider>
    );
};

const defaultLanguageContext: LanguageContextProps = {
    language: 'zh',
    toggleLanguage: () => {},
    setLanguage: () => {},
    t: (key: string) => translations.zh[key] || translations.en[key] || key,
};

export const useLanguage = (): LanguageContextProps => {
    const context = useContext(LanguageContext);
    return context || defaultLanguageContext;
};
